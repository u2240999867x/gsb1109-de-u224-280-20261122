"""Align streaming DataFrame branches by original-item provenance.

This module implements an opt-in "align columns by original item" usage for
streaming dataframes.  Independent branches (for example boxes and fees
expanded from the same waybills) are combined so that every output row
receives exactly the values that belong to it: values produced *by* an item
are collected for that item only, while values belonging to a containing
item (for example an insurance amount held at waybill level) are broadcast
to every retained descendant.

Provenance travels in the stream ``metadata`` channel rather than in table
columns, so business code keeps using ``query``, column projection,
``reset_index`` and friends as usual while inspectors can still trace every
row back to its original batch, original item and original position.

Table operations that do not opt into this usage are unaffected.
"""

import itertools
import logging
from collections import namedtuple

import numpy as np
import pandas as pd

from ..core import Stream
from ..collection import Streaming, map_partitions as _map_partitions
from .core import DataFrame
from .utils import is_dataframe_like

logger = logging.getLogger(__name__)

PROVENANCE_KEY = 'provenance'


class RowRef(namedtuple('RowRef', ['batch', 'path'])):
    """ Pointer to a row of an original (possibly nested) batch element

    Parameters
    ----------
    batch: hashable
        Identifier of the emitted batch the row belongs to.  Display values
        such as the Pandas index or business keys may repeat across batches;
        the batch identifier is what keeps them apart.
    path: tuple
        Positions navigating the original nested structure, e.g. ``(1,)``
        for the second waybill row, ``(1, 2)`` for its third box and
        ``(1, 2, 0)`` for the first fee of that box.  Expanding the same
        original list independently yields the same refs, so branches can
        recognize the same original item.
    """
    __slots__ = ()

    def parent(self):
        """ Ref of the containing original item """
        if not self.path:
            raise ValueError("Top-level RowRef has no parent")
        return RowRef(self.batch, self.path[:-1])

    def child(self, position):
        """ Ref of the child at ``position`` in this item's original list """
        return RowRef(self.batch, self.path + (position,))

    def __repr__(self):
        return 'RowRef(%r, (%s))' % (self.batch, ', '.join(map(str, self.path)))


class ProvenanceRecord(object):
    """ Provenance of one emitted partition

    Parameters
    ----------
    batch: hashable
        Batch this partition belongs to.
    rows: list
        One entry per row of the accompanying partition.  Entries produced
        by ``explode``/``emit`` are :class:`RowRef` objects; entries
        produced by :func:`align` are dictionaries holding the contributing
        refs of every attached branch.
    final: bool
        True when this partition completes ``batch`` for the emitting
        branch.  A branch may deliver a batch in several shards; only the
        last one is final.
    universe: frozenset of RowRef
        Every ref generated by ``explode`` operations upstream.  This
        records which original items existed, even if their rows were later
        filtered out of the partition itself.
    """
    __slots__ = ('batch', 'rows', 'final', 'universe')

    def __init__(self, batch, rows, final=True, universe=frozenset()):
        self.batch = batch
        self.rows = list(rows)
        self.final = final
        self.universe = frozenset(universe)

    def take(self, indices):
        """ New record keeping only (and reordering to) the given row positions """
        return ProvenanceRecord(self.batch, [self.rows[i] for i in indices],
                                final=self.final, universe=self.universe)

    def with_rows(self, rows, extra_universe=()):
        """ New record with replaced rows and optionally extended universe """
        return ProvenanceRecord(self.batch, list(rows), final=self.final,
                                universe=self.universe | frozenset(extra_universe))

    def __repr__(self):
        return 'ProvenanceRecord(batch=%r, rows=%r, final=%r)' % (
            self.batch, self.rows, self.final)


def provenance_metadata(record):
    """ Wrap a record into a stream metadata entry """
    return {PROVENANCE_KEY: record}


def get_provenance(metadata):
    """ Extract the provenance record from a stream metadata list, if any """
    for entry in metadata or []:
        if isinstance(entry, dict) and PROVENANCE_KEY in entry:
            return entry[PROVENANCE_KEY]
    return None


class ProvenanceError(Exception):
    """ A branch referenced an original item that does not exist

    Carries the offending ``batch`` and the ``ref`` (original position) so
    the problematic batch can be reported and dropped without delivering
    partial results.
    """

    def __init__(self, batch, ref):
        self.batch = batch
        self.ref = ref
        super(ProvenanceError, self).__init__(
            "batch %r: row at original position %s points to an item that "
            "does not exist in the original batch" % (batch, ref))


class map_provenance(Stream):
    """ Map data and provenance metadata together

    ``func`` transforms the partition while ``prov_func(record, x, result)``
    computes the provenance record of the transformed partition.  This is
    how row correspondence is preserved through row-changing operations.
    """

    def __init__(self, upstream, func, prov_func):
        self.func = func
        self.prov_func = prov_func
        Stream.__init__(self, upstream)

    def update(self, x, who=None, metadata=None):
        result = self.func(x)
        record = get_provenance(metadata)
        if record is None:
            return self._emit(result, metadata=metadata)
        new_record = self.prov_func(record, x, result)
        new_metadata = [provenance_metadata(new_record)
                        if isinstance(m, dict) and PROVENANCE_KEY in m else m
                        for m in metadata]
        return self._emit(result, metadata=new_metadata)


def _as_provenance_func(correspondence):
    """ Normalize a user supplied row correspondence into a prov_func

    A correspondence may be

    - a callable ``(record, x, result) -> ProvenanceRecord | refs | positions``
    - a list of positions into the input rows
    - a list of explicit refs for the output rows
    """
    if callable(correspondence):
        def prov_func(record, x, result):
            return _normalize_correspondence(
                correspondence(record, x, result), record)
        return prov_func
    if isinstance(correspondence, (list, tuple)):
        static = list(correspondence)
        return lambda record, x, result: _normalize_correspondence(static, record)
    raise TypeError("Unsupported provenance correspondence: %r" % (correspondence,))


def _normalize_correspondence(value, record):
    if isinstance(value, ProvenanceRecord):
        return value
    value = list(value)
    if all(isinstance(v, (int, np.integer)) for v in value):
        return record.take(value)
    return record.with_rows(value)


class ProvenanceDataFrame(DataFrame):
    """ A streaming DataFrame whose rows carry provenance in stream metadata

    Behaves like a regular streaming ``DataFrame``; row-preserving
    operations (projection, ``reset_index``, ``assign``, ...) keep the
    provenance untouched automatically, while row-changing operations
    (``query``, ``explode``) transform it accordingly.  Custom partition
    functions that change row correspondence can declare it explicitly via
    the ``provenance`` keyword of ``map_partitions``.
    """

    def __init__(self, *args, **kwargs):
        super(ProvenanceDataFrame, self).__init__(*args, **kwargs)
        self._batch_ids = itertools.count()

    def emit(self, x, batch=None, final=True, rows=None, asynchronous=False):
        """ Emit a partition together with its provenance

        Parameters
        ----------
        x: DataFrame
            The partition to emit.
        batch: hashable, optional
            Batch identifier.  Auto-assigned when omitted.
        final: bool
            Whether this partition completes ``batch`` for this branch.
        rows: list of RowRef, optional
            Explicit provenance for the rows of ``x``.  By default rows are
            attributed to their position in this batch element.
        """
        self.verify(x)
        if batch is None:
            batch = next(self._batch_ids)
        if rows is None:
            rows = [RowRef(batch, (i,)) for i in range(len(x))]
        record = ProvenanceRecord(batch, rows, final=final)
        return self.stream.emit(x, asynchronous=asynchronous,
                                metadata=[provenance_metadata(record)])

    def _map_provenance(self, func, prov_func, example=None):
        if example is None:
            example = func(self.example)
        stream = map_provenance(self.stream, func, prov_func)
        return ProvenanceDataFrame(stream, example)

    def map_partitions(self, func, *args, **kwargs):
        provenance = kwargs.pop('provenance', None)
        if not args or not isinstance(args[0], Streaming):
            args = (self,) + args
        if provenance is None:
            # Row-preserving operations let the metadata flow through
            result = _map_partitions(func, *args, **kwargs)
            if (isinstance(result, DataFrame)
                    and not isinstance(result, ProvenanceDataFrame)
                    and is_dataframe_like(result.example)):
                return ProvenanceDataFrame(result.stream, result.example)
            return result
        # Row-changing custom function: the caller provides the
        # correspondence between input and output rows explicitly.
        if any(isinstance(arg, Streaming) for arg in args[1:]):
            raise TypeError("Explicit provenance correspondence only "
                            "supports literal extra arguments")
        example = kwargs.pop('example', None)
        if example is None:
            example = func(*[getattr(arg, 'example', arg) for arg in args],
                           **kwargs)
        frame = args[0]

        def data_func(x):
            return func(x, *args[1:], **kwargs)

        stream = map_provenance(frame.stream, data_func,
                                _as_provenance_func(provenance))
        return ProvenanceDataFrame(stream, example)

    def query(self, expr, **kwargs):
        """ Query, keeping provenance attached to the surviving rows """
        eval_kwargs = {k: kwargs[k] for k in ('engine', 'parser') if k in kwargs}

        def func(df):
            return df.query(expr, **kwargs)

        def prov_func(record, x, result):
            mask = list(x.eval(expr, **eval_kwargs))
            return record.take([i for i, keep in enumerate(mask) if keep])

        return self._map_provenance(func, prov_func)

    def explode(self, column):
        """ Explode a list-like column, attributing each element its position

        Elements keep their position in the original list, so independently
        exploding the same original list on another branch recognizes the
        same original item.
        """
        def func(df):
            return df.explode(column)

        def prov_func(record, x, result):
            rows = []
            universe = set(record.universe)
            for ref, values in zip(record.rows, x[column]):
                if isinstance(values, (list, tuple, np.ndarray)) and len(values):
                    for position in range(len(values)):
                        child = ref.child(position)
                        rows.append(child)
                        universe.add(child)
                else:
                    rows.append(ref.child(None))
            if len(rows) != len(result):
                raise ValueError(
                    "Exploded provenance (%d rows) does not match exploded "
                    "data (%d rows)" % (len(rows), len(result)))
            return ProvenanceRecord(record.batch, rows, final=record.final,
                                    universe=frozenset(universe))

        return self._map_provenance(func, prov_func)


class Attach(object):
    """ How to attach one branch onto the base rows in :func:`align`

    Parameters
    ----------
    frame: ProvenanceDataFrame
        The branch to attach.
    column: str
        Column of the branch holding the values to attach.
    into: str
        Name of the output column to create on the base rows.
    kind: 'collect' or 'broadcast'
        ``collect``: gather the values of rows whose provenance descends
        from each base row, ordered by original position, into a list
        (e.g. the fees produced by one box).  ``broadcast``: copy the
        scalar value of the nearest ancestor row (e.g. the insurance of the
        containing waybill) onto every retained descendant.
    """

    def __init__(self, frame, column, into, kind='collect'):
        if kind not in ('collect', 'broadcast'):
            raise ValueError("kind must be 'collect' or 'broadcast', got %r"
                             % (kind,))
        self.frame = frame
        self.column = column
        self.into = into
        self.kind = kind


class align_provenance(Stream):
    """ Combine branches per batch once every branch confirmed completion

    Buffers the partitions of every upstream per batch.  A batch is
    delivered exactly once, when all upstreams marked it final.  Batches
    missing confirmations stay pending and are never mistaken for completed
    empty batches.  Rows pointing to original items that do not exist are
    reported on the ``errors`` stream; their batch is dropped without
    partial results and later batches proceed normally.
    """

    def __init__(self, base, specs):
        self.specs = list(specs)
        upstreams = [base.stream] + [spec.frame.stream for spec in self.specs]
        self.pending = {}
        self.delivered = set()
        self.errors = Stream(stream_name='align-errors')
        Stream.__init__(self, upstreams=upstreams)

    def update(self, x, who=None, metadata=None):
        record = get_provenance(metadata)
        if record is None:
            raise ValueError("align requires provenance metadata on all "
                             "upstreams")
        index = self.upstreams.index(who)
        batch = record.batch
        if batch in self.delivered:
            return
        state = self.pending.setdefault(batch, {
            'parts': {i: [] for i in range(len(self.upstreams))},
            'final': set(),
            'universe': set(),
        })
        state['parts'][index].append((x, record))
        state['universe'] |= set(record.universe)
        if record.final:
            state['final'].add(index)
        if len(state['final']) < len(self.upstreams):
            return
        self.delivered.add(batch)
        del self.pending[batch]
        try:
            out, rows = self._combine(state, batch)
        except ProvenanceError as error:
            logger.error("Dropping batch: %s", error)
            self.errors._emit(error)
            return
        record = ProvenanceRecord(batch, rows, final=True,
                                  universe=frozenset(state['universe']))
        return self._emit(out, metadata=[provenance_metadata(record)])

    def _combine(self, state, batch):
        base_frames = [df for df, _ in state['parts'][0]]
        base_refs = [ref for _, rec in state['parts'][0] for ref in rec.rows]
        out = pd.concat(base_frames, ignore_index=True)
        combined_rows = [{'origin': ref} for ref in base_refs]

        for position, spec in enumerate(self.specs, start=1):
            entries = []
            for df, rec in state['parts'][position]:
                entries.extend(zip(rec.rows, df[spec.column]))
            if spec.kind == 'collect':
                self._attach_collect(spec, entries, state, batch, out,
                                     base_refs, combined_rows)
            else:
                self._attach_broadcast(spec, entries, out,
                                       base_refs, combined_rows)
        return out, combined_rows

    def _attach_collect(self, spec, entries, state, batch, out, base_refs,
                        combined_rows):
        universe = state['universe']
        parents = {ref.parent() for ref in universe if ref.path}
        by_parent = {}
        for ref, value in entries:
            parent = ref.parent() if ref.path else None
            if parent in universe:
                by_parent.setdefault(parent, []).append((ref, value))
            elif parent is not None and parent.path and parent.parent() in parents:
                # The containing item was expanded by the base branch, so
                # all of its original children are known: this row points
                # to an original item that does not exist.
                raise ProvenanceError(batch, ref)
            # Otherwise the containing item never reached the base branch
            # (e.g. filtered out upstream); its values are dropped quietly.
        column = []
        for ref, row in zip(base_refs, combined_rows):
            matches = sorted(by_parent.get(ref, []), key=lambda rv: rv[0].path)
            column.append([value for _, value in matches])
            row[spec.into] = [match_ref for match_ref, _ in matches]
        out[spec.into] = pd.Series(column, dtype=object)

    def _attach_broadcast(self, spec, entries, out, base_refs, combined_rows):
        column = []
        for ref, row in zip(base_refs, combined_rows):
            best = None
            for candidate, value in entries:
                if (candidate.batch == ref.batch
                        and ref.path[:len(candidate.path)] == candidate.path):
                    if best is None or len(candidate.path) > len(best[0].path):
                        best = (candidate, value)
            column.append(best[1] if best is not None else None)
            row[spec.into] = best[0] if best is not None else None
        if column:
            out[spec.into] = pd.Series(column)
        else:
            dtype = spec.frame.example[spec.column].dtype
            out[spec.into] = pd.Series([], dtype=dtype, index=out.index)


def align(base, attach=()):
    """ Align branches onto ``base`` rows by original-item provenance

    Parameters
    ----------
    base: ProvenanceDataFrame
        The branch whose rows define the output rows and their order.
    attach: list of Attach
        Branches to attach onto the base rows.

    Returns
    -------
    ProvenanceDataFrame
        Emits one partition per batch, exactly once, after every branch
        confirmed completion of that batch.  The provenance of each output
        row is a dictionary with the base row's ref under ``'origin'`` and
        the contributing refs of every attached branch under its ``into``
        name.  Batches with invalid references are reported on the
        ``.errors`` stream of the returned object and dropped.
    """
    specs = list(attach)
    node = align_provenance(base, specs)
    example = base.example.iloc[:0].copy()
    for spec in specs:
        if spec.kind == 'collect':
            example[spec.into] = pd.Series([], dtype=object)
        else:
            dtype = spec.frame.example[spec.column].dtype
            example[spec.into] = pd.Series([], dtype=dtype)
    result = ProvenanceDataFrame(node, example)
    result.errors = node.errors
    return result


class _provenance_stream(Stream):
    def update(self, x, who=None, metadata=None):
        record = get_provenance(metadata)
        if record is not None:
            return self._emit(record)


def provenance_of(frame):
    """ Stream of the ProvenanceRecord of every partition emitted by ``frame``

    Lets inspectors trace each emitted row back to its original batch,
    original item and original position without carrying source fields as
    table columns.
    """
    stream = getattr(frame, 'stream', frame)
    return _provenance_stream(stream)
